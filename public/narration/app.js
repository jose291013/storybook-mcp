function applyCopy(language) {
  const locale = String(language || "fr").slice(0, 2).toLowerCase();
  copy = COPY[locale] || COPY.fr;
  document.querySelectorAll("[data-i18n]").forEach((node) => { node.textContent = copy[node.dataset.i18n] || node.textContent; });
}

function option(item, name, selected) {
  const label = document.createElement("label"); label.className = "option";
  const input = document.createElement("input"); input.type = "radio"; input.name = name; input.value = item.id; input.checked = item.id === selected;
  label.append(input, document.createTextNode(item.label));
  if (item.description) { const small = document.createElement("small"); small.textContent = item.description; label.append(small); }
  return label;
}
function choice() {
  selectedVoice = document.querySelector('input[name="voice"]:checked')?.value || "";
  selectedStyle = document.querySelector('input[name="style"]:checked')?.value || "";
  const choiceLocked = ["wait", "retry"].includes(actionMode);
  document.querySelectorAll('input[name="voice"], input[name="style"]').forEach((input) => { input.disabled = choiceLocked; });
  elements.consent.disabled = choiceLocked;
  elements.buy.disabled = actionMode === "wait"
    || (actionMode !== "retry" && !(selectedVoice && selectedStyle && elements.consent.checked));
  elements.sample.disabled = choiceLocked || !(selectedVoice && selectedStyle);
}

function renderAction(hasActiveNarration = false) {
  if (actionMode === "replace") {
    elements.status.textContent = copy.ready;
    elements.buy.textContent = copy.replace;
  } else if (actionMode === "retry") {
    elements.status.textContent = copy.failed;
    elements.buy.textContent = copy.retry;
  } else if (actionMode === "wait") {
    elements.status.textContent = hasActiveNarration ? copy.replacing : copy.generating;
    elements.buy.textContent = copy.inProgress;
  } else {
    elements.status.textContent = copy.compare;
    elements.buy.textContent = copy.buy;
  }
  choice();
}
async function start() {
  try {
    const response = await fetch(`/api/projects/${encodeURIComponent(projectId)}/narration`, { cache: "no-store" });
    const data = await response.json();
    if (response.status === 401) { location.assign(`/api/auth/woocommerce/narration?projectId=${encodeURIComponent(projectId)}`); return; }
    if (!response.ok) throw new Error(data.error || "Narration indisponible");
    const current = data.aiNarration || {};
    selectedVoice = current.voiceId || data.catalog.voices[0].id; selectedStyle = current.styleId || data.catalog.styles[0].id;
    data.catalog.voices.forEach((item) => elements.voices.append(option(item, "voice", selectedVoice)));
    data.catalog.styles.forEach((item) => elements.styles.append(option(item, "style", selectedStyle)));
    document.documentElement.lang = data.project.language.slice(0, 2);
    applyCopy(data.project.language);
    actionMode = data.nextAction || "purchase";
    elements.content.hidden = false;
    document.addEventListener("change", choice);
    renderAction(Boolean(data.hasActiveNarration));
  } catch (error) { elements.status.textContent = error.message; }
}
elements.sample.addEventListener("click", async () => {
  choice(); elements.sample.disabled = true; elements.sample.textContent = copy.preparing;
  elements.audio.src = `/api/projects/${encodeURIComponent(projectId)}/narration-sample?voiceId=${encodeURIComponent(selectedVoice)}&styleId=${encodeURIComponent(selectedStyle)}&t=${Date.now()}`;
  try { await elements.audio.play(); } catch {}
  elements.sample.textContent = copy.replay; elements.sample.disabled = false;
});
elements.buy.addEventListener("click", async () => {
  choice(); if (elements.buy.disabled) return;
  const retrying = actionMode === "retry";
  elements.buy.disabled = true; elements.buy.textContent = retrying ? copy.retrying : copy.opening;
  try {
    const endpoint = retrying ? "narration-retry" : "narration-checkout-link";
    const options = retrying
      ? { method: "POST" }
      : { method: "POST", headers: { "Content-Type": "application/json" }, body: JSON.stringify({ voiceId: selectedVoice, styleId: selectedStyle }) };
    const response = await fetch(`/api/projects/${encodeURIComponent(projectId)}/${endpoint}`, options);
    const data = await response.json(); if (!response.ok) throw new Error(data.error || "Narration indisponible");
    if (!retrying) { location.assign(data.checkoutUrl); return; }
    actionMode = "wait"; renderAction(false);
  } catch (error) { elements.status.textContent = error.message; renderAction(false); }
});
applyCopy("fr");
start();
